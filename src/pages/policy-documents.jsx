import Section from '../components/Section'
import './policy-documents.css'
import { BASE_DATA } from '../funcs/BASE_DATA'
import aiGeneratedImage from "../assets/ai-generated-image.png"
import { useState } from 'react'


export const NoAIPolicyPage = () => {
    const [heropageIndex, setHeroPageIndex] = useState(0);
    const heroParagraphs = [
        (<>
        <p>We at {BASE_DATA.STUDIO_NAME} are witnessing the influence and rapid growth of AI (Artificial Intelligence). It has permeated everything, from education to entertainment to writing to warfare. Over the past three years that AI in its current form has been around, it has truly affected the world like no other technology.</p>
        </>),
        (<>
        <p>And while we do see the potential advantages and benefits of AI, we also see the downsides and the negative effects of using the technology. AI might be a really powerful tool, but it is also a dangerous tool.</p>
        </>)
    ]

    return (
        <>
        <Section title={BASE_DATA.STUDIO_NAME + "'s AI Policy"}/>
        <Section background_img_style={`url(${aiGeneratedImage})`} height={500} title='Our Stance on AI' description={(<>
            {heroParagraphs[heropageIndex]}
            <div className='navigator'>
                 <button disabled={heropageIndex === 0} onClick={() => setHeroPageIndex((heropageIndex - 1 + heroParagraphs.length) % heroParagraphs.length)}>Previous</button>
                 <p>{heropageIndex + 1}/{heroParagraphs.length}</p>
                <button disabled={heropageIndex === heroParagraphs.length - 1} onClick={() => setHeroPageIndex((heropageIndex + 1) % heroParagraphs.length)}>Next</button>
               
            </div>
            <p>* Background generated by AI</p>
            </>)}/>
        <Section height={200} title='Pros and Cons of AI'/>
        <div className='split-section'>
            <Section>
                <Section title='Pros'/>
                <Section/>
            </Section>
             <Section>
                <Section title='Cons'/>
            </Section>
        </div>
        </>
    )
}